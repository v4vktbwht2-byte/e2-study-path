type PartOfSpeech = VocabularyItem["partOfSpeech"];

interface VocabularySeedOptions {
  lemma?: string;
  synonyms?: readonly string[];
  antonyms?: readonly string[];
  confusionGroupIds?: readonly string[];
  extraTags?: readonly string[];
}

interface VocabularySeed {
  headword: string;
  partOfSpeech: PartOfSpeech;
  meaningJa: string;
  exampleEn: string;
  exampleJa: string;
  topic: string;
  collocation: string;
  options: VocabularySeedOptions;
}

interface StageVocabularySeeds {
  stage: CurriculumStage;
  entries: readonly VocabularySeed[];
}

function vocab(
  headword: string,
  partOfSpeech: PartOfSpeech,
  meaningJa: string,
  exampleEn: string,
  exampleJa: string,
  topic: string,
  collocation: string,
  options: VocabularySeedOptions = {},
): VocabularySeed {
  return {
    headword,
    partOfSpeech,
    meaningJa,
    exampleEn,
    exampleJa,
    topic,
    collocation,
    options,
  };
}

