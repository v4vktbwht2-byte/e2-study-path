function slugifyHeadword(headword: string): string {
  return headword
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "");
}

function createVocabularyItem(
  stage: CurriculumStage,
  seed: VocabularySeed,
): VocabularyItem {
  const slug = slugifyHeadword(seed.headword);
  const id = `vocab-s${stage}-${slug}`;
  const usageTag = seed.headword.includes(" ") ? "form:phrase" : "form:word";

  return {
    id,
    schemaVersion: "1.0.0",
    contentRevision: 1,
    stage,
    headword: seed.headword,
    lemma: seed.options.lemma ?? seed.headword,
    partOfSpeech: seed.partOfSpeech,
    meanings: [
      {
        id: "primary",
        ja: seed.meaningJa,
        register: "neutral",
      },
    ],
    exampleSentences: [
      {
        id: `${id}-example-1`,
        en: seed.exampleEn,
        ja: seed.exampleJa,
        stage,
      },
    ],
    collocations: [seed.collocation],
    synonyms: [...(seed.options.synonyms ?? [])],
    antonyms: [...(seed.options.antonyms ?? [])],
    confusionGroupIds: [...(seed.options.confusionGroupIds ?? [])],
    tags: [
      "original",
      "vocabulary",
      `stage:${stage}`,
      `part-of-speech:${seed.partOfSpeech}`,
      `topic:${seed.topic}`,
      `search:${seed.topic}`,
      usageTag,
      ...(seed.options.extraTags ?? []),
    ],
    source: ORIGINAL_CONTENT_SOURCE,
  };
}

export const pilotVocabulary: readonly VocabularyItem[] = stageVocabularySeeds.flatMap(
  ({ stage, entries }) => entries.map((entry) => createVocabularyItem(stage, entry)),
);
